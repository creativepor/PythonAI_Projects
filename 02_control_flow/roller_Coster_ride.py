# Enter your height and Age and check if the 
# kid is eligible for the roller coster ride in theme park

height = int(input("Enter your height in cm: "))
age = int(input("Enter your age: "))

if height >= 120 and age >=18:
    print("You are eligible to ride the Roller Coaster")
else:
    print("You are not eligible to ride the Roller Coaster")
    