# Lesson 1.2: Variables and Basic Data Types
# Learn about numbers (int, float), strings (str), and booleans (bool).

# 1. Variables
name = "Learner"
age = 25
height = 5.9
is_student = True

# 2. Printing with f-strings (formatted strings)
print(f"Name: {name} (Type: {type(name).__name__})")
print(f"Age: {age} (Type: {type(age).__name__})")
print(f"Height: {height} (Type: {type(height).__name__})")
print(f"Is Student: {is_student} (Type: {type(is_student).__name__})")

